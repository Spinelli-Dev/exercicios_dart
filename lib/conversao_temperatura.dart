void main(List<String> arguments) {
  // Crie uma variável contendo uma temperatura em Celsius e converta para Fahrenheit.
  // Fahrenheit = (Celsius x 9 / 5) + 32

  var celsius = 38.0;
  var fahrenheit = (celsius * 9 / 5) + 32;

  print("A temperatura $celsiusº celsius é igual a $fahrenheitº fahrenheit.");
}